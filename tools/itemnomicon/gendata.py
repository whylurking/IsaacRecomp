# Itemnomicon: writes rt/mod_itemnomicon_data.inc from texts.py and the measured stat changes (measured_*.json).
#   python3 tools/itemnomicon/gendata.py
# Stat lines: measured speed, damage, range (|change| >= 0.5: below that it's the game's random tear height),
# shot speed, heart containers, soul hearts and pickups (only for the items that give them: other pickups could be
# collected while measuring); tears from the game's own tear formula (firr(), per version), because Ipecac, Mutant
# Spider and Polyphemus leave the triple-shot flag (ups[2]) set after they're removed. Active items: no stat lines
# (giving one replaces the previous one, so its numbers are relative); The Whore of Babylon: conditional.
