SOUL={72,79,80,92,182}
CONS={17:'keys',18:'coins',19:'bombs',74:'coins',106:'bombs',125:'bombs',137:'bombs',140:'bombs',190:'bombs'}
NAMES={'speed':'Speed','tears':'Tears','damage':'Damage','range':'Range','shotspeed':'Shot speed'}
import math
def tears(g, ups):
    u=lambda k: ups.get(k,0)
    if g=='og': l=u(6)*1.5+(u(32)+u(80)+u(1)+u(120))*0.7+u(59)*0.4+(u(101)+u(90))*0.2
    else: l=u(6)*1.5+(u(32)+u(80)+u(1)+u(120))*0.7+(u(196)+u(59)-u(182)*(2.3 if g=='eternal' else 1))*0.4+(u(101)+u(90)+u(189))*0.2
    if u(120): l+=1
    if g=='og': fire=max(5,16-math.sqrt(1+l*1.3)*6)
    else: fire=max(5,16-math.sqrt(max(0,1+l*1.3))*6-min(l,0)*6)
    if u(69): fire*=0.8
    if u(2): fire=fire*2.1+3
    return 30/(fire+1)
def tearDelta(g,i):
    ups={i:1}
    if i in (149,153,169): ups[2]={149:0.5,153:0.4,169:0.3}[i]
    return tears(g,ups)-tears(g,{})
def lines(i, d, g):
    out=[]
    d=dict(d); d['tears']=tearDelta(g,i)
    if i==122: return out
    if i not in ACT:
        for k in ['damage','tears','speed','range','shotspeed']:
            v=d.get(k,0)
            if k=='range' and abs(v)<0.5: continue
            if abs(v)<0.05: continue
            out.append(('+' if v>0 else '-')+'%s %s%.2f'%(NAMES[k],'+' if v>0 else '-',abs(v)))
        m=d.get('mhp',0)
        if m>0: out.append('++%d heart container%s'%(m,'' if m==1 else 's'))
        elif m<0: out.append('-Heart containers: only one left')
        if i in SOUL and d.get('soul',0)>0:
            s=d['soul']; out.append('++%d soul heart%s'%(s,'' if s==1 else 's'))
    if i in CONS and d.get(CONS[i],0)>0:
        out.append('++%d %s'%(d[CONS[i]],CONS[i]))
    return out
